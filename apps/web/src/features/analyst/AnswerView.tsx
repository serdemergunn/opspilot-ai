import type { ChatResponse, Finding, FindingKind } from "../../api/chat";

/**
 * Each kind has its own label, icon and border style, so the distinction never depends on color alone.
 * Measurements and calculations are verified against tool results; hypotheses are explicitly unverified.
 */
export const KIND_STYLE: Record<FindingKind, { label: string; icon: string; className: string }> = {
  measurement: { label: "Verified measurement", icon: "✓", className: "border-l-[3px] border-l-[#2a78d6] bg-white" },
  calculation: { label: "Calculated statistic", icon: "Σ", className: "border-l-[3px] border-l-[#2a78d6] bg-white" },
  pattern: { label: "Pattern", icon: "≈", className: "border-l-[3px] border-l-[#6250d6] bg-white" },
  hypothesis: { label: "Hypothesis · not verified", icon: "?", className: "border border-dashed border-[#c98500] bg-[#fffaf0]" },
  recommendation: { label: "Suggested action", icon: "→", className: "border-l-[3px] border-l-[#008300] bg-white" },
};

const KIND_ORDER: FindingKind[] = ["measurement", "calculation", "pattern", "hypothesis", "recommendation"];

export function ModeBadge({ response }: { response: ChatResponse }) {
  return response.mode === "demo" ? (
    <span className="inline-flex items-center gap-1 rounded border border-hairline bg-page px-1.5 py-0.5 text-[11px] text-ink-secondary">
      <span aria-hidden>◆</span> Demo mode · deterministic answer, not generated by an LLM
    </span>
  ) : (
    <span className="inline-flex items-center gap-1 rounded border border-hairline bg-page px-1.5 py-0.5 text-[11px] text-ink-secondary">
      <span aria-hidden>●</span> Live · {response.provider}
    </span>
  );
}

export function AnswerView({ response, onSelectTool }: { response: ChatResponse; onSelectTool: (toolCallId: string) => void }) {
  const tools = new Map(response.tool_calls.map((t) => [t.id, t]));
  const findings = [...response.findings].sort((a, b) => KIND_ORDER.indexOf(a.kind) - KIND_ORDER.indexOf(b.kind));
  return (
    <div className="space-y-3">
      <div className="flex flex-wrap items-center gap-2">
        <ModeBadge response={response} />
        <span className="text-[11px] text-ink-muted">
          {response.usage.tool_calls} tool call{response.usage.tool_calls === 1 ? "" : "s"} ·{" "}
          {response.timeline.reduce((s, t) => s + t.duration_ms, 0).toLocaleString("en-US")} ms
        </span>
      </div>
      <p className="text-sm leading-6 text-ink">{response.summary}</p>

      {response.warnings.length > 0 && (
        <ul className="space-y-1 rounded-md border border-[#fab219]/60 bg-[#fffaf0] px-3 py-2 text-xs text-ink">
          {response.warnings.map((w) => (
            <li key={w} className="flex gap-1.5">
              <span aria-hidden className="font-bold text-[#c98500]">!</span>
              <span>
                <span className="sr-only">Warning: </span>
                {w}
              </span>
            </li>
          ))}
        </ul>
      )}

      {findings.length > 0 && (
        <ul className="space-y-2" aria-label="Findings">
          {findings.map((f) => (
            <FindingItem key={f.id} finding={f} toolName={(id) => tools.get(id)?.tool ?? id} onSelectTool={onSelectTool} />
          ))}
        </ul>
      )}
    </div>
  );
}

function FindingItem({ finding, toolName, onSelectTool }: { finding: Finding; toolName: (id: string) => string; onSelectTool: (id: string) => void }) {
  const style = KIND_STYLE[finding.kind];
  return (
    <li className={`rounded-md px-3 py-2 ${style.className}`}>
      <p className="mb-0.5 flex items-center gap-1.5 text-[11px] font-medium uppercase tracking-wide text-ink-secondary">
        <span aria-hidden className="inline-flex h-4 w-4 items-center justify-center rounded bg-page text-[10px] text-ink">{style.icon}</span>
        {style.label}
        {finding.grounding !== "no_numbers" && (
          <span className="normal-case tracking-normal text-ink-muted">
            · {finding.grounding === "verified" ? "numbers match tool results" : "difference of tool values"}
          </span>
        )}
      </p>
      <p className={`text-sm leading-6 text-ink ${finding.kind === "hypothesis" ? "italic" : ""}`}>{finding.text}</p>
      {finding.evidence.length > 0 && (
        <p className="mt-1 flex flex-wrap gap-1">
          {finding.evidence.map((e) => (
            <button
              key={e.tool_call_id}
              type="button"
              onClick={() => onSelectTool(e.tool_call_id)}
              className="rounded border border-hairline bg-page px-1.5 py-px font-mono text-[10px] text-ink-secondary hover:border-[#2a78d6] hover:text-ink"
              title="Show this tool call"
            >
              source: {toolName(e.tool_call_id)}
            </button>
          ))}
        </p>
      )}
    </li>
  );
}
